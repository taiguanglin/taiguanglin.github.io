    sess = sess[0]
    cues = parse_srt_raw(sess['media_parts'][0]['srt_file'])
    ncues = [(s, e, _norm(x)) for s, e, x in cues]   # 匹配用正規化 cue
    print(f"session={sess['session_id']} cues={len(cues)}")
    print(f"{'#':>3} {'start':>9} {'end':>9} {'firstword':<14} {'判定':<9} 詳情")

    n_late = n_unknown = 0
    for g in sess['segments']:
        st, en = g['start'], g.get('end')
        if st is None or en is None:
            print(f"{g['index']:>3} {'—':>9} {'—':>9} {'':<14} {'SKIP':<9} 空答案佔位段（start/end=None，不佔音檔時間）")
            continue
        fw = first_word(g['answer_text'] or g.get('q_text') or '')
        vs = [_norm(v) for v in variants(fw)]
        hit = None
        for i, (s, e, x) in enumerate(ncues):
            if e < st - 4 or s > st + 8:
                continue
            if any(v in x for v in vs):
                hit = (i, s, e, x)
                break
            # split-cue 合併比對：名字／題幹被 ASR 拆到相鄰 2-3 條 cue
            # （如 缘起尘微→这些缘|起尘灰、失眠的问题→失眠|的问|题、先拜众生→先拜众|生再拜）
            for _k in (2, 3):
                _j = i + _k - 1
                if _j >= len(ncues):
                    break
                _s2, _e2 = ncues[i][0], ncues[_j][1]
                if _e2 < st - 4 or _s2 > st + 8:
                    continue
                _xc = ''.join(ncues[_t][2] for _t in range(i, _j + 1))
                if any(v in _xc for v in vs):
                    hit = (i, _s2, _e2, _xc)
                    break
            if hit:
                break
        # 唸回先於變形 hit（name 未轉出、變形只命中後續內容）：段落起點所落 cue 在
        # start 後 ≤1.5s 起步且第一個變形 hit 距 start >1.5s → 以該 cue 改判（回退唸回）
        if hit is not None and st < hit[1] - 0.15 and hit[1] - st > 1.5:
            ci0 = next((i for i, (s, e, x) in enumerate(ncues) if s <= st <= e), None)
            if ci0 is not None and ci0 < hit[0]:
                i, s, e, x = ci0, ncues[ci0][0], ncues[ci0][1], ncues[ci0][2]
                hit = (i, s, e, x)
        ci = next((i for i, (s, e, x) in enumerate(cues) if s <= st <= e), None)
        if ci is not None:
            s, e, x = cues[ci]
            ctx = f'cue[{ci}]{s:.2f}-{e:.2f}:{x[:26]}'
        else:
            nxt = next(((i, s, e, x) for i, (s, e, x) in enumerate(cues) if s >= st), None)
            ctx = (f'SILENCE→cue[{nxt[0]}]{nxt[1]:.2f}:{nxt[3][:26]}' if nxt else 'SILENCE')

        if hit is None:
            # 空窗／壞轉錄檢查：start 前 ≥5s 未轉錄區（SRT 盲區）→ SKIP；
            # 或 start 落點 cue 為 ≤2 字殘句（如「，」「好吧」）且該 cue 前有 ≥5s 空窗
            # → SRT 該區轉錄壞損＋時戳漂移，同樣無法驗證（需 FunASR 字級 onset）
            _nxt = next(((s2, e2) for s2, e2, _ in cues if s2 >= st), None)
            _prev = max((e2 for _s2, e2, _ in cues if e2 <= st), default=None)
            gap_note = None
            if _nxt and _prev and _prev <= st <= _nxt[0] and _nxt[0] - _prev >= 5:
                gap_note = (f'SRT 未轉錄空窗（{_prev:.2f}–{_nxt[0]:.2f}，{_nxt[0]-_prev:.1f}s）：'
                            'start 在空窗內，SRT 無法驗證（需 FunASR 字級 onset）')
            else:
                ci0 = next((i2 for i2, (s2, e2, _x) in enumerate(cues) if s2 <= st <= e2), None)
                if ci0 is not None:
                    _s2, _e2, _x2 = cues[ci0]
                    _bare = len(re.sub(r'[\s，。、？！,.\'?!,。』」]', '', _x2))
                    _p2 = max((e3 for _s3, e3, _x3 in cues if e3 <= _s2), default=None)
                    # ≤2 字殘句：無論前方是否有空窗，姓名／答案開頭皆未轉錄（如「以后，」「，」）
                    if _bare <= 2:
                        _gtxt = (f'（前有 {_s2-_p2:.1f}s 未轉錄空窗）'
                                 if _p2 is not None and _s2 - _p2 >= 5 else '')
                        gap_note = (f'壞轉錄 cue[{ci0}]{_s2:.2f}-{_e2:.2f}:「{_x2[:10]}」{_gtxt}'
                                    f'（cue 僅 {_bare} 字）：'
                                    'SRT 該區轉錄壞損，無法驗證（需 FunASR 字級 onset）')
            # 唸回題幹：段以「唸回自己 q_text」開頭（Word 文字省略唸回）→ 合法
            qraw = re.sub(r'^[\s\d、.．（）()【】\[\]]+', '', g.get('q_text') or '')
            qfw = first_word(qraw) if qraw else None
            if qfw:
                qvs = [_norm(v) for v in variants(qfw)]
                for i, (s, e, x) in enumerate(ncues):
                    if e < st - 4 or s > st + 8:
                        continue
                    if any(v in x for v in qvs):
                        verdict = 'OK'
                        detail = f'cue[{i}]{s:.2f}-{e:.2f}:{x[:26]} (唸回題幹，屬本段)'
                        break
                else:
                    if gap_note:
                        verdict, detail = 'SKIP', gap_note
                    else:
                        verdict, n_unknown = '???', n_unknown + 1
                        detail = f'{ctx} | ±8s 內未找到第一詞 cue（先推 ASR 串再反查）'
            else:
                if gap_note:
                    verdict, detail = 'SKIP', gap_note
                else:
                    verdict, n_unknown = '???', n_unknown + 1
                    detail = f'{ctx} | ±8s 內未找到第一詞 cue（先推 ASR 串再反查）'
        else:
            i, s, e, x = hit
            if s - 0.15 <= st <= e + 0.15:
                verdict = 'OK'
                detail = f'cue[{i}]{s:.2f}-{e:.2f}:{x[:26]} (start 在 cue 內)'
            elif st < s - 0.15:
                verdict = ('EARLY' if s - st <= 1.5 else 'LATE')
                if verdict == 'LATE':
                    n_late += 1
                detail = f'cue[{i}]{s:.2f}-{e:.2f}:{x[:26]} (start 提前 {s - st:.2f}s)'
            else:
                # hit cue 整個在 start 前（落後）——先排除 prev-tail 誤命中：
                # 從 start 起重掃變形 cue，存在且在 EARLY 合法窗（≤1.5s）內即改判
                re2 = next(((i2, s2, e2, x2) for i2, (s2, e2, x2) in enumerate(ncues)
                            if st - 0.15 <= s2 <= st + 8 and any(v in x2 for v in vs)), None)
                if re2 is not None and re2[1] - st <= 1.5:
                    i, s, e, x = re2
                    if st >= s - 0.15:
                        verdict = 'OK'
                        detail = f'cue[{i}]{s:.2f}-{e:.2f}:{x[:26]} (prev-tail 誤命中改判：真第一詞 cue 從 start 起)'
                    else:
                        verdict = 'EARLY'
                        detail = f'cue[{i}]{s:.2f}-{e:.2f}:{x[:26]} (prev-tail 誤命中改判：start 提前 {s - st:.2f}s)'
                else:
                    verdict, n_late = 'LATE', n_late + 1
                    detail = f'cue[{i}]{s:.2f}-{e:.2f}:{x[:26]} (start 落後 {st - s:.2f}s)'
        print(f"{g['index']:>3} {st:>9.3f} {en:>9.3f} {fw:<14} {verdict:<9} {detail}")

    # 銜接校驗（closing 佔在兩段之間時，#a.end==closing.start 即為合法銜接）
    # 音訊序：JSON 序≠音訊序的月份（word-chrono 朗讀順序不同），鏈以 start 排序後校驗
    segs = sess['segments']
    closing = sess.get('closing') or {}
    cl_s, cl_e = closing.get('start'), closing.get('end')   # closing=None 的場跳過 closing 銜接檢查
    real = [g for g in segs if g.get('start') is not None and g.get('end') is not None]
    real.sort(key=lambda g: g['start'])

    def _chain_ok(a, b):
        if a.get('end') == b['start']:
            return True
        if cl_s is not None and cl_e is not None and cl_s >= a.get('end', -1) and cl_e <= b['start'] + 0.16:
            return True   # closing 佔在兩段之間（收場段在鏈上）
        return False

    # 空答案佔位段（start/end=None）在鏈上透明：只校驗實段（real 已按音訊序排序）
    chain_bad = [(a['index'], a.get('end'), b['start'])
                 for a, b in zip(real, real[1:]) if not _chain_ok(a, b)]
    print(f"\n=== LATE: {n_late}  ???(ASR 變形需判讀): {n_unknown}  鏈斷點: {chain_bad or '無'}")
    print("=== EARLY ≤1.5s 為合法（golden 同款）；LATE/prev-tail 需修；??? 先推 ASR 串再反查")
    return 0


