def parse_srt_raw(p):
    """-> [(start_s, end_s, text), ...] 毫秒原值"""
    txt = Path(p).read_text(encoding='utf-8', errors='replace')
    cues = []
    for m in re.finditer(
        r'(\d+):(\d+):(\d+)[,.](\d+)\s*-->\s*(\d+):(\d+):(\d+)[,.](\d+)\s*\n(.*?)(?=\n\s*\n|\Z)',
        txt, re.S,
    ):
        g = m.groups()
        s = int(g[0]) * 3600000 + int(g[1]) * 60000 + int(g[2]) * 1000 + int(g[3])
        e = int(g[4]) * 3600000 + int(g[5]) * 60000 + int(g[6]) * 1000 + int(g[7])
        cues.append((s / 1000.0, e / 1000.0, m.group(9).strip().replace('\n', ' ')))
    return cues


def first_word(text):
    t = (text or '').strip()
    # Word 時間戳殘留（如 （29.47））
    t = re.sub(r'^(?:[（(][^）)]*[）)])+', '', t)
    m = re.match(r'^([\u4e00-\u9fffA-Za-z0-9_]{1,8})', t)
    if m:
        return m.group(1)
    # 非匹配前綴（如 ༺ཌༀ Mr A）
    m = re.search(r'[\u4e00-\u9fffA-Za-z0-9_]{1,8}', t)
    return m.group(0) if m else t[:8]


def variants(w):
    """正字 -> [正字 + ASR 變形]；尾端數字常被唸成中文或併入語氣詞，另給去數字段"""
    out = [w]
    core = re.sub(r'[0-9]+$', '', w)
    if not core:
        core = w   # 純數字 fw（如 q 編號「2、」被 first_word 取成「2」）不去數字，避免空串全 cue 誤命中
    if core != w:
        out.append(core)
    for k, vs in VAR.items():
        if core.startswith(k) or k == core or w.startswith(k):
            bases = {core}
            if w.startswith(k):
                bases.add(w)
            for base in bases:
                out += [base.replace(k, v) for v in vs]
        elif k.startswith(w) and len(w) >= 4:
            out += list(vs)   # 字被 regex 截短（如 AuntSall→AuntSally）——直接給變形
    # regex 截斷／ASR 變形在尾端（如 wxpcjrjgcs→WXPCJRZGCS 第 7 字 j↔z）——
    # 再給遞減前綴（≥4 字，避免過短誤命中；唸回常只唸前 4 字，如 先拜众生再拜佛→先拜众生）；
    # ASR 變形後的串也要給前綴（如 《坐禅》中讲到神→就餐中讲到神→只匹配到「就餐中讲到」）
    seen = set(out)
    grown = True
    while grown:
        grown = False
        for v in list(seen):
            for n in range(len(v) - 1, 3, -1):
                p = v[:n]
                if p not in seen:
                    seen.add(p)
                    grown = True
    out = [w] + [x for x in seen if x != w]
    return out


def _norm(s):
    """匹配用正規化：去空白（ASR 在字母旁加空格）＋去《》（ASR 常略去書名號）＋忽略大小寫"""
    return re.sub(r'[\s《》]+', '', s).lower()


